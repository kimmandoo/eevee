#!/usr/bin/env python3
"""Render the pinned cargo-about report, including packaged upstream notices."""
import argparse
import json
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()
    report = json.loads(Path(args.report).read_text(encoding="utf-8"))
    covered = {use["crate"]["id"] for license in report["licenses"] for use in license["used_by"]}
    required = {entry["package"]["id"] for entry in report["crates"]}
    assert required and required <= covered, f"license text missing for {sorted(required - covered)}"
    output = ["Eevee / ev — third-party notices\n",
              "Generated by cargo-about 0.9.2 from the locked native dependency graph.\n",
              "Project code is Apache-2.0; dependency terms below remain their own.\n",
              "No franchise image bytes are bundled. Code licensing does not grant image or trademark rights.\n"]
    project_notice = Path(__file__).resolve().parents[1] / "NOTICE"
    output.append("\nProject attribution notice\n" + "=" * 72 + "\n")
    output.append(project_notice.read_text(encoding="utf-8").rstrip() + "\n")
    for license in report["licenses"]:
        assert license["text"].strip(), "empty dependency license text"
        output.append("\n" + "=" * 72 + "\n" + license["name"] + " (" + license["id"] + ")\n")
        for use in license["used_by"]:
            crate = use["crate"]
            output.append(f"  {crate['name']} {crate['version']} — {crate.get('repository') or crate.get('source') or 'local project'}\n")
            if crate.get("authors"):
                output.append("    Authors: " + "; ".join(crate["authors"]) + "\n")
        output.append("\n" + license["text"].rstrip() + "\n")
    for entry in report["crates"]:
        crate = entry["package"]
        directory = Path(crate["manifest_path"]).parent
        for name in ("NOTICE", "NOTICE.txt", "NOTICE.md", "NOTICES", "NOTICES.txt", "COPYRIGHT"):
            notice = directory / name
            if notice.resolve() == project_notice:
                continue
            if notice.exists():
                assert notice.is_file() and not notice.is_symlink() and notice.stat().st_size <= 1024 * 1024, f"invalid upstream notice: {notice}"
                output.append(f"\n{'=' * 72}\n{crate['name']} {crate['version']} — upstream {name}\n")
                output.append(notice.read_text(encoding="utf-8").rstrip() + "\n")
    destination = Path(args.output)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("".join(output), encoding="utf-8")
    print(f"Recorded license text for {len(required)} native packages: {destination}")


if __name__ == "__main__":
    main()
